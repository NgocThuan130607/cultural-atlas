// Packs every JSON file in public/data into one plain script, public/data/atlas-data.js:
//   window.ATLAS_DATA = { "cities.json": {...}, "landmarks/eiffel-tower.json": {...}, ... }
// Browsers block fetch() on pages opened straight from disk (file://), but a <script> still loads,
// so this lets the built site run by double-clicking index.html. Runs automatically before dev and build.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const dataDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'data');

async function jsonFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries.map((e) => (e.isDirectory() ? jsonFiles(join(dir, e.name)) : e.name.endsWith('.json') ? [join(dir, e.name)] : [])));
  return nested.flat().sort();
}

const data = {};
for (const file of await jsonFiles(dataDir)) {
  data[relative(dataDir, file).split(sep).join('/')] = JSON.parse(await readFile(file, 'utf8'));
}
const out = `// Generated by scripts/bundle-data.mjs from the JSON files in this folder. Don't edit by hand.\nwindow.ATLAS_DATA = ${JSON.stringify(data)};\n`;
await writeFile(join(dataDir, 'atlas-data.js'), out);
console.log(`Bundled ${Object.keys(data).length} data files into public/data/atlas-data.js (${Math.round(out.length / 1024)} KB).`);
