// Writes docs/image-sources.md: every Wikimedia Commons image the site shows, with author, licence and link.
// Run: npm run sources
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'public', 'data');
const media = JSON.parse(await readFile(join(dataDir, 'media.json'), 'utf8'));

// Collect every { "file": "..." } image reference, with the page it appears on.
const used = new Map();
const collect = (node, where) => {
  if (Array.isArray(node)) return node.forEach((n) => collect(n, where));
  if (!node || typeof node !== 'object') return;
  if (typeof node.file === 'string') {
    const key = node.file.replace(/_/g, ' ');
    if (!used.has(key)) used.set(key, new Set());
    used.get(key).add(where);
  }
  Object.values(node).forEach((v) => collect(v, where));
};
for (const dir of ['cities', 'landmarks']) {
  for (const f of (await readdir(join(dataDir, dir))).sort()) {
    const d = JSON.parse(await readFile(join(dataDir, dir, f), 'utf8'));
    collect(d, `${dir === 'cities' ? 'city' : 'landmark'}: ${d.name ?? f.replace('.json', '')}`);
  }
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\|').replace(/\s+/g, ' ').trim();
const rows = [...used.keys()].sort((a, b) => a.localeCompare(b)).map((file) => {
  const m = media[file] ?? {};
  return `| ${cell(file)} | ${cell(m.artist)} | ${cell(m.license)} | ${cell([...used.get(file)].join('; '))} | ${m.page ?? ''} |`;
});
await mkdir(join(root, 'docs'), { recursive: true });
await writeFile(join(root, 'docs', 'image-sources.md'), `# Image sources

All ${rows.length} photos and drawings shown on the site come from Wikimedia Commons (https://commons.wikimedia.org).
None were made with generative AI. Each page also lists its own image credits at the bottom.
Generated by \`npm run sources\` from \`public/data/media.json\`.

| File | Author | Licence | Used on | Source |
|---|---|---|---|---|
${rows.join('\n')}
`);
console.log(`docs/image-sources.md: ${rows.length} images`);
